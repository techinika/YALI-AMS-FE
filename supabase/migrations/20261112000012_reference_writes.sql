-- Allow the dashboard to create reference rows without supplying an id.
--
-- The migration script preserves legacy ids, so new rows need a safe default:
--   * cohorts.id is an int with legacy values starting at 1 -> identity
--   * tracks.id / working_sectors.id are text -> server-side uuid text
--
-- This migration is additive and never rewrites existing ids.

alter table public.cohorts alter column id add generated by default as identity;
select setval(
  pg_get_serial_sequence('public.cohorts', 'id'),
  coalesce((select max(id) from public.cohorts), 0) + 1,
  false
);

alter table public.tracks alter column id set default (gen_random_uuid())::text;
alter table public.working_sectors alter column id set default (gen_random_uuid())::text;